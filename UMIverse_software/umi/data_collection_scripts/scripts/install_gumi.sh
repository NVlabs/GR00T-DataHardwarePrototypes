# Link umi_dc and dexumi_dc from the shared root .venv into ~/.local/bin;
# gumi aliases umi_dc. Links stay tied to this checkout.
# Run after uv sync: ./scripts/install_gumi.sh [--quiet]. No sudo is required.












set -euo pipefail

GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
UMI_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
# The repository root, which holds the uv workspace and its .venv.
REPO_ROOT="$(cd "$UMI_ROOT/../../.." && pwd)"
VENV_BIN="$REPO_ROOT/.venv/bin"

QUIET=0
[ "${1:-}" = "--quiet" ] && QUIET=1

say() { [ "$QUIET" -eq 1 ] || echo -e "${GREEN}✓${NC} $1"; }
warn() { echo -e "${YELLOW}⚠${NC} $1"; }

BIN_DIR="${HOME}/.local/bin"
mkdir -p "$BIN_DIR"

# Link the venv commands so upgrades take effect without copying wrappers
# and arguments reach the installed launcher unchanged.



for cmd in umi_dc dexumi_dc; do
    ln -sfn "$VENV_BIN/$cmd" "$BIN_DIR/$cmd"
done
say "Linked umi_dc and dexumi_dc in $BIN_DIR to $VENV_BIN"
if [ ! -x "$VENV_BIN/umi_dc" ] || [ ! -x "$VENV_BIN/dexumi_dc" ]; then
    warn "$VENV_BIN has no umi_dc or dexumi_dc yet: run 'uv sync' in $REPO_ROOT first"
fi

# gumi uses the installed environment without dependency resolution.
# Remove any existing link before writing its wrapper to avoid modifying
# the link target.


GUMI="${BIN_DIR}/gumi"
rm -f "$GUMI"
cat > "$GUMI" <<EOF
#!/usr/bin/env bash
# UMI station console, same as umi_dc -- installed by scripts/install_gumi.sh.
# Do not edit; it is regenerated by setup_station.sh and install_gumi.sh.
[ "\${1:-}" = "offline" ] && shift
exec "$VENV_BIN/umi_dc" "\$@"
EOF
chmod +x "$GUMI"
say "Installed $GUMI (same as umi_dc)"

# A leftover ~/.bashrc alias would shadow the gumi executable in bash. Remove it
# so the wrapper is the only `gumi`.
BASHRC="${HOME}/.bashrc"
if [ -f "$BASHRC" ] && grep -qE "^[[:space:]]*alias gumi=" "$BASHRC" 2>/dev/null; then
    tmpfile=$(mktemp)
    grep -vE "^[[:space:]]*alias gumi=" "$BASHRC" > "$tmpfile" && mv "$tmpfile" "$BASHRC"
    say "Removed the old 'gumi' alias from $BASHRC (the wrapper replaces it)"
fi

# Add ~/.local/bin to the login shell configuration only when missing from PATH.


case ":$PATH:" in
    *":$BIN_DIR:"*)
        say "$BIN_DIR is already on PATH -- run: umi_dc  or  dexumi_dc"
        ;;
    *)
        SHELL_RC="${HOME}/.bashrc"
        case "${SHELL:-}" in
            *zsh) SHELL_RC="${HOME}/.zshrc" ;;
        esac
        PATH_LINE='export PATH="$HOME/.local/bin:$PATH"'
        if ! grep -qF "$PATH_LINE" "$SHELL_RC" 2>/dev/null; then
            echo "" >> "$SHELL_RC"
            echo "# Added by UMI install_gumi.sh so umi_dc and dexumi_dc are on PATH" >> "$SHELL_RC"
            echo "$PATH_LINE" >> "$SHELL_RC"
        fi
        warn "$BIN_DIR was not on PATH; added it to $SHELL_RC"
        echo "  Run:  source $SHELL_RC   (or open a new terminal), then: umi_dc  or  dexumi_dc"
        ;;
esac
